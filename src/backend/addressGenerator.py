from faker import Faker
import re
from exceptions.exceptions import InvalidGenerationException
from backend.address import Address
from typing import Union, Match

def generateCompanyName(fake: Faker) -> str:
    """Generates a random company name using the given Faker."""
    return fake.company()

# Regex for addresses with localization de_DE
ADDRESS_REGEX = r'^(.*) (\d+(?:[\-/]\d+|[a-z])?)\n(\d{5}) (.*?)\s*$'

def generateAddress(fake: Faker) -> Address:
    """
    Generates a random Address consisting of street, housenumber, plz and town using the given faker.
    Raises an InvalidGenerationException if the address generated by the faker does not match the expected regex,
    which can happen if localization other than de_DE is used.
    """
    address: str = fake.address()
    matcher: Union[Match[str], None] = re.match(ADDRESS_REGEX, address)
    if not matcher:
        raise InvalidGenerationException()
    return Address(matcher.group(1), matcher.group(2), matcher.group(3), matcher.group(4))